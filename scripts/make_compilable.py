#!/usr/bin/env python3
"""Комплексное превращение dog2.txt в компилируемую версию МАДЛЕН."""
import sys

src = '/home/azizz/old_dispak/re-dispak/МРВ/dog2.txt'
dst = sys.argv[1] if len(sys.argv) > 1 else 'dog2_compilable.txt'

with open(src, encoding='utf-8') as f:
    lines = f.readlines()

log = []

def rep(n, old, new):
    """Заменить в исходной строке n (1-based)."""
    i = n - 1
    assert old in lines[i], (n, old, lines[i])
    lines[i] = lines[i].replace(old, new, 1)
    log.append(f'{n}: {old!r} -> {new!r}')

def insert_after(n, newlines):
    i = n
    lines[i:i] = newlines
    log.append(f'после {n}: вставлено {len(newlines)} строк')

# ---------- 1. Метки в колонке 0 ----------
for n in (36, 40, 48, 157, 162, 232, 456):
    i = n - 1
    assert lines[i][0] not in ' \t', (n, lines[i])
    lines[i] = ' ' + lines[i]
    log.append(f'{n}: метка в колонке 0 -> с ведущим пробелом')

# ---------- 3. Восстановленный комментарий (OCR потерял точку) ----------
for i, l in enumerate(lines):
    if 'IS TASK НЕ 1-Й РАЗ' in l:
        lines[i] = l.replace('IS TASK НЕ', 'IS TASK .НЕ')
        log.append(f'{i+1}: восстановлена точка перед комментарием "НЕ 1-Й РАЗ"')
        break

# ---------- 4. Пропущенные двоеточия в метках ----------
for lno, old, new in [
    (1254, 'SP 4     , ITA', 'SP 4     : , ITA'),
    (1261, 'SP3      , BSS', 'SP3      : , BSS'),
]:
    rep(lno, old, new)

# ---------- 5. Исправления опечаток OCR в именах ----------
# (делаем до вставки блоков, чтобы номера строк совпадали с оригиналом)
fixes = [
    # пропущенные/испорченные операнды и имена
    (801,  'NEXT PCT', 'NEX PCT'),
    (806,  'NEXT PCT', 'NEX PCT'),
    (831,  'NEXT PCT', 'NEX PCT'),
    (1145, 'NEXT PCT', 'NEX PCT'),
    (833,  'P BSE B',  'PBASE B'),
    (1512, 'NO9/1',    'N09/1'),
    (1417, 'INIT 00',  'ININT00'),
    (1135, 'SW COM',   'CW COM'),
    # литералы: ISO-константы требуют префикса '='
    (124,  '5H GLAV',  '=5H GLAV'),
    (125,  '5H ТЕК',   '=5H ТЕК'),
    # литералы: действительные константы требуют точки
    (288,  '=R5',  '=R5.'),
    (379,  '=R4',  '=R4.'),
    (1216, '=R3',  '=R3.'),
    (1427, '=R1',  '=R1.'),
    (1468, '=R2',  '=R2.'),
    # восьмеричные литералы требуют префикса '='
    (803,  '17 7777.', '=17 7777 .'),
    (819,  '7 4000',  '=7 4000'),
    (931,  '17 7774', '=17 7774'),
    # комментарий с ведущим пробелом в колонке 1
    (623,  ' C  , CALL', 'C  , CALL'),
    # индексный регистр при VTM
    (789,  ', VTM ,-3', '3, VTM ,-3'),
    # опечатка мнемоники AAB -> AAX
    (1403, 'AAB', 'AAX'),
    # лишний '*' перед ISO-литералом
    (1582, 'AUX ,*6H', 'AUX ,=6H'),
    # символы, отсутствующие в кодировке KOI-7 ассемблера
    (1686, '6H-↑-↑-↑', '6H------'),
    (1817, '3^', '3>'),
    # пропущенная запятая в команде
    (714,  '15, AOX', '15, AOX ,'),

    # пропущена точка перед комментарием
    (1528, '=377   2 ЦИФРЫ', '=377   .2 ЦИФРЫ'),
]
for n, old, new in fixes:
    rep(n, old, new)

# continuation-комментарий без маркера в колонке 1 (строка 942)
assert 'В БУФЕРЕ ДЛЯ СПРАВКИ.' in lines[941]
lines[941] = 'С В БУФЕРЕ ДЛЯ СПРАВКИ.\n'
log.append('942: продолжение комментария -> С в колонке 1')

# ---------- 5а. Дубль *15 (после всех правок по номерам строк) ----------
assert lines[190].strip().startswith('*15') and lines[189].strip().startswith('*15')
del lines[190]
log.append('191: удалён дубль метки *15')

# ---------- 6. Блок объявлений сразу после NAME ----------
name_idx = next(i for i, l in enumerate(lines) if l.strip().startswith('DOG') and ',NAME,' in l)
block = [
    'C==========================================\n',
    'C ВОССТАНОВЛЕННЫЕ ОБЪЯВЛЕНИЯ (ДЛЯ КОМПИЛЯЦИИ)\n',
    'C КОММЕНТАРИИ СОДЕРЖАТ ИСТОЧНИК СВЕДЕНИЙ:\n',
    'C ТАБЛИЦА ССЫЛОК ЛИСТИНГА DOG, СТР.44-48 PDF\n',
    'C И ЛИСТИНГ КАРТ DOG02760, DOG02880 И ДР.\n',
    'C------------------------------------------\n',
    'C ВНЕШНИЕ ПОДПРОГРАММЫ ПЕЧАТИ\n',
]
for s in ['PRINTS', 'PRINTK', 'PRPR2', 'PRV', 'PRV1', 'PRV2', 'PRV3'] + \
         [f'PRINT{i}' for i in range(1, 21)]:
    block.append(f' {s:9}: ,SUBP,\n')
block += [
    'C------------------------------------------\n',
    'C ВОССТАНОВЛЕННЫЕ ДАННЫЕ И КОНСТАНТЫ\n',
]
defs = [
    ('E4000',    'EQU', '76B',   '.КОНСТАНТА (ТАБЛ.ССЫЛОК 00076)'),
    ('DESH',     'BSS', '16',    '.ДЕШИФРАТОР (КАРТА DOG02880)'),
    ('ISTASK',   'BSS', '',      '.ПРИЗНАК ЗАДАЧИ (КАРТА DOG02760)'),
    ('IS4',      'BSS', '',      '.МЕТКА IS 4 (ТАБЛ.ССЫЛОК 00430)'),
    ('EVPTASK',  'BSS', '',      '.СОБЫТИЕ В ПЗ (ТАБЛ.ССЫЛОК 01134)'),
    ('MTADMPB',  'BSS', '1',     '.МАССИВ ЗАДАЧ МРВ'),
    ('MTADMBPD', 'BSS', '1',     '.МАССИВ ЗАДАЧ МРВ (D)'),
    ('OUTFIELD', 'BSS', '1',     '.ПОЛЕ ВЫВОДА'),
    ('TABRAS',   'BSS', '1',     '.ТАБЛИЦА ДИАГНОСТИКИ'),
    ('SYM',      'BSS', '1',     '.КОД ОШИБКИ'),
    ('BTASK',    'BSS', '1',     '.БЛОК ЗАДАЧ'),
    ('T1',       'BSS', '1',     '.ВРЕМЕННАЯ 1'),
    ('T2',       'BSS', '1',     '.ВРЕМЕННАЯ 2'),
    ('T3',       'BSS', '1',     '.ВРЕМЕННАЯ 3'),
    ('T4',       'BSS', '1',     '.ВРЕМЕННАЯ 4'),
    ('T5',       'BSS', '1',     '.ВРЕМЕННАЯ 5'),
    ('BUFCOM6',  'LOG', '6',     '.БУФЕР КОМАНД 6'),
    ('TEXT55',   'GOST', '6HТЕКСТ', '.ТЕКСТ СООБЩЕНИЯ'),
    ('EWC',      'BSS', '1',     '.ИНДЕКС ПОЛЯ ПАРАМЕТРОВ'),
    ('REGCOM',   'BSS', '1',     '.РЕГИСТР КОМАНДЫ'),
    ('CLP',      'BSS', '',      '.КОНЕЦ ЦИКЛА ОЧИСТКИ'),
    ('REQPZ',    'BSS', '',      '.ЗАПРОС К ПЗ'),
    ('IPTASK',   'BSS', '1',     '.ПОЛЕ УПРЯТЫВАНИЯ ПЗ'),
    ('N',        'EQU', '10B',   '.КОНСТАНТА N'),
    ('ISSHTEK',  'BSS', '1',     '.УКАЗАТЕЛЬ SH TEK'),
    ('DEBREG',   'BSS', '15',    '.РЕГИСТРЫ ОТЛАДЧИКА (PROMON)'),
    ('S',        'BSS', '1',     '.ВСПОМОГАТЕЛЬНАЯ'),
]
for name, d, arg, cm in defs:
    block.append(f' {name:10}: ,{d:4}, {arg} {cm}\n')
block.append('C==========================================\n')
lines[name_idx + 1:name_idx + 1] = block
log.append(f'после строки 1: добавлен блок объявлений ({len(block)} строк)')

# ---------- 7. MM3: EQU после определения MM2 ----------
# MM2 находится в исходной строке 272; после вставок ищем её по тексту
for i, l in enumerate(lines):
    if l.lstrip().startswith('MM2 :'):
        lines[i + 1:i + 1] = [' MM3       : ,EQU ,MM2  .КОНЕЦ ЦИКЛА КОПИРОВАНИЯ\n']
        log.append(f'после строки {i+1}: MM3 = MM2 (EQU)')
        break

# ---------- 8. END ----------
if not any(l.strip().upper().startswith(', END') for l in lines[-5:]):
    lines.append('         , END ,\n')
    log.append('добавлен , END ,')

with open(dst, 'w', encoding='utf-8') as f:
    f.writelines(lines)

for x in log:
    print(x)
print(f'Итого: {len(lines)} строк -> {dst}')
